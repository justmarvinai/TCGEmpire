// Generates the seed SQL from content/. Idempotent: safe to apply on every deploy.
//   supabase/seed/config.sql   balance values
//   supabase/seed/catalog.sql  sets, cards (with calibrated values), products, quest templates, tutorial
import { writeFileSync } from 'node:fs'
import { config } from '../content/config.ts'
import { cardValues, PRODUCTS, SETS } from '../content/catalog.ts'
import { MINI_QUESTS } from '../content/quests.ts'
import { TUTORIAL } from '../content/tutorial.ts'

const q = (v: string | null | undefined) => (v == null ? 'null' : `'${v.replace(/'/g, "''")}'`)
const rows = (list: string[]) => list.map((r) => `  (${r})`).join(',\n')

export function buildConfigSql(): string {
  return [
    '-- GENERATED by scripts/gen-seed.ts from content/. Do not edit by hand.',
    'insert into game.config (key, value) values',
    rows(Object.entries(config).map(([k, v]) => `${q(k)}, ${q(JSON.stringify(v))}::jsonb`)),
    'on conflict (key) do update set value = excluded.value;',
    '',
  ].join('\n')
}

export function buildCatalogSql(): string {
  const out = ['-- GENERATED by scripts/gen-seed.ts from content/. Do not edit by hand.']
  // The phase of a set is decided by the admin at runtime and never overwritten here.
  out.push(
    'insert into game.set_defs (id, game, name, size) values',
    rows(SETS.map((s) => `${q(s.id)}, ${q(s.game)}, ${q(s.name)}, ${s.size}`)),
    'on conflict (id) do update set game = excluded.game, name = excluded.name, size = excluded.size;',
  )
  for (const s of SETS) {
    const values = cardValues(s)
    out.push(
      'insert into game.card_defs (id, set_id, no, name, tier, kind, element, value_base_cents) values',
      rows(
        s.cards.map(
          (c) => `${q(c.id)}, ${q(s.id)}, ${c.no}, ${q(c.name)}, ${q(c.tier)}, ${q(c.kind)}, ${q(c.element)}, ${values.get(c.id)}`,
        ),
      ),
      'on conflict (id) do update set set_id = excluded.set_id, no = excluded.no, name = excluded.name, tier = excluded.tier,',
      '  kind = excluded.kind, element = excluded.element, value_base_cents = excluded.value_base_cents;',
    )
  }
  out.push(
    'insert into game.product_defs (id, set_id, kind, name, price_base_cents, slots) values',
    rows(
      PRODUCTS.map(
        (p) => `${q(p.id)}, ${q(p.set)}, ${q(p.kind)}, ${q(p.name)}, ${p.priceBaseCents}, ${q(JSON.stringify(p.slots))}::jsonb`,
      ),
    ),
    'on conflict (id) do update set set_id = excluded.set_id, kind = excluded.kind, name = excluded.name,',
    '  price_base_cents = excluded.price_base_cents, slots = excluded.slots;',
    'insert into game.quest_templates (key, event, min_target, max_target) values',
    rows(MINI_QUESTS.map((t) => `${q(t.key)}, ${q(t.event)}, ${t.min}, ${t.max}`)),
    'on conflict (key) do update set event = excluded.event, min_target = excluded.min_target, max_target = excluded.max_target;',
    'insert into game.tutorial_steps (step, event, reward_booster, reward_base_cents, reward_ep) values',
    rows(TUTORIAL.map((s, i) => `${i}, ${q(s.event)}, ${s.reward.booster ?? 0}, ${s.reward.cents ?? 0}, ${s.reward.ep ?? 0}`)),
    'on conflict (step) do update set event = excluded.event, reward_booster = excluded.reward_booster,',
    '  reward_base_cents = excluded.reward_base_cents, reward_ep = excluded.reward_ep;',
    `delete from game.tutorial_steps where step >= ${TUTORIAL.length};`,
    '',
  )
  return out.join('\n')
}

if (process.argv[1]?.endsWith('gen-seed.ts')) {
  writeFileSync(new URL('../supabase/seed/config.sql', import.meta.url), buildConfigSql())
  writeFileSync(new URL('../supabase/seed/catalog.sql', import.meta.url), buildCatalogSql())
  console.log('wrote supabase/seed/config.sql and catalog.sql')
}

// Generates the seed SQL from content/. Idempotent: safe to apply on every deploy.
//   supabase/seed/config.sql   balance values
//   supabase/seed/catalog.sql  sets, cards (with calibrated values), products, quest templates, tutorial
import { writeFileSync } from 'node:fs'
import { config } from '../content/config.ts'
import { cardValues, isEnergy, PRODUCTS, SETS } from '../content/catalog.ts'
import { QUESTS_BY_KIND } from '../content/quests.ts'
import { UNLOCKS } from '../content/unlocks.ts'
import { UPGRADES } from '../content/upgrades.ts'
import { JOBS } from '../content/jobs.ts'
import { CONSUMABLES } from '../content/consumables.ts'
import { ACHIEVEMENTS } from '../content/achievements.ts'
import { TUTORIAL } from '../content/tutorial.ts'
import { NPCS } from '../content/npcs.ts'
import { STORES } from '../content/stores.ts'
import { RIVALS } from '../content/rivals.ts'
import { GOALS } from '../content/goals.ts'
import { SKILL_COST, SKILLS } from '../content/skills.ts'
import { FURNISHING_SLOTS, FURNITURE, HOMES } from '../content/housing.ts'
import { COSMETICS } from '../content/cosmetics.ts'
import { COMPANY_CONFIG } from '../content/company.ts'
import { EVENTS_CONFIG } from '../content/events.ts'
import { DARKSIDE_CONFIG } from '../content/darkside.ts'
import { BARES_CONFIG } from '../content/bares.ts'
import { PRESTIGE_CONFIG } from '../content/prestige.ts'

const q = (v: string | null | undefined) => (v == null ? 'null' : `'${v.replace(/'/g, "''")}'`)
const rows = (list: string[]) => list.map((r) => `  (${r})`).join(',\n')

export function buildConfigSql(): string {
  return [
    '-- GENERATED by scripts/gen-seed.ts from content/. Do not edit by hand.',
    'insert into game.config (key, value) values',
    rows(
      [...Object.entries(config), ...Object.entries(COMPANY_CONFIG), ...Object.entries(EVENTS_CONFIG), ...Object.entries(DARKSIDE_CONFIG), ...Object.entries(BARES_CONFIG), ...Object.entries(PRESTIGE_CONFIG), ...Object.entries(UNLOCKS).map(([k, v]) => [`unlock.${k}`, v] as const)].map(
        ([k, v]) => `${q(k)}, ${q(JSON.stringify(v))}::jsonb`,
      ),
    ),
    'on conflict (key) do update set value = excluded.value;',
    '',
  ].join('\n')
}

export function buildCatalogSql(): string {
  const out = ['-- GENERATED by scripts/gen-seed.ts from content/. Do not edit by hand.']
  // The phase of a set is decided by the admin at runtime and never overwritten here.
  out.push(
    'insert into game.set_defs (id, game, name, size) values',
    rows(SETS.map((s) => `${q(s.id)}, ${q(s.game)}, ${q(s.name)}, ${s.size}`)),
    'on conflict (id) do update set game = excluded.game, name = excluded.name, size = excluded.size;',
  )
  for (const s of SETS) {
    const values = cardValues(s)
    out.push(
      'insert into game.card_defs (id, set_id, no, name, tier, kind, element, value_base_cents) values',
      rows(
        s.cards.map(
          // the server knows one resource kind: Riftbound runes fill the energy slot like Pokémon energies
          (c) => `${q(c.id)}, ${q(s.id)}, ${c.no}, ${q(c.name)}, ${q(c.tier)}, ${q(isEnergy(c) ? 'energy' : c.kind)}, ${q(c.element)}, ${values.get(c.id)}`,
        ),
      ),
      'on conflict (id) do update set set_id = excluded.set_id, no = excluded.no, name = excluded.name, tier = excluded.tier,',
      '  kind = excluded.kind, element = excluded.element, value_base_cents = excluded.value_base_cents;',
    )
  }
  out.push(
    'insert into game.product_defs (id, set_id, kind, name, price_base_cents, slots, contents) values',
    rows(
      PRODUCTS.map(
        (p) => `${q(p.id)}, ${q(p.set)}, ${q(p.kind)}, ${q(p.name)}, ${p.priceBaseCents}, ${q(JSON.stringify(p.slots))}::jsonb, ${p.contains ? `${q(JSON.stringify(p.contains))}::jsonb` : 'null'}`,
      ),
    ),
    'on conflict (id) do update set set_id = excluded.set_id, kind = excluded.kind, name = excluded.name,',
    '  price_base_cents = excluded.price_base_cents, slots = excluded.slots, contents = excluded.contents;',
    'insert into game.quest_templates (key, event, min_target, max_target, kind, min_level) values',
    rows(
      Object.entries(QUESTS_BY_KIND).flatMap(([kind, list]) =>
        list.map((t) => `${q(t.key)}, ${q(t.event)}, ${t.min}, ${t.max}, ${q(kind)}, ${t.minLevel ?? 1}`),
      ),
    ),
    'on conflict (key) do update set event = excluded.event, min_target = excluded.min_target, max_target = excluded.max_target,',
    '  kind = excluded.kind, min_level = excluded.min_level;',
    'insert into game.upgrade_defs (key, grp, max_level, cost_base_cents, growth, min_level, level_step, stat, op, per_level) values',
    rows(
      UPGRADES.map(
        (u) =>
          `${q(u.key)}, ${q(u.group)}, ${u.max}, ${u.costBaseCents}, ${u.growth}, ${u.minLevel}, ${u.levelStep}, ${q(u.stat)}, ${q(u.op)}, ${u.per ?? 'null'}`,
      ),
    ),
    'on conflict (key) do update set grp = excluded.grp, max_level = excluded.max_level, cost_base_cents = excluded.cost_base_cents,',
    '  growth = excluded.growth, min_level = excluded.min_level, level_step = excluded.level_step, stat = excluded.stat,',
    '  op = excluded.op, per_level = excluded.per_level;',
    'insert into game.skill_defs (key, branch, tier, cost, requires, stat, op, value) values',
    rows(
      SKILLS.map(
        (s) =>
          `${q(s.key)}, ${q(s.branch)}, ${s.tier}, ${SKILL_COST[s.tier]}, array[${s.requires.map((r) => q(r)).join(', ')}]::text[], ${q(s.stat)}, ${q(s.op)}, ${s.value}`,
      ),
    ),
    'on conflict (key) do update set branch = excluded.branch, tier = excluded.tier, cost = excluded.cost, requires = excluded.requires,',
    '  stat = excluded.stat, op = excluded.op, value = excluded.value;',
    'insert into game.home_defs (tier, key, min_level, price_base_cents, wohnwert, slots, lager_units, vitrine_slots, energy_regen_pct) values',
    rows(HOMES.map((h) => `${h.tier}, ${q(h.key)}, ${h.minLevel}, ${h.priceBaseCents}, ${h.wohnwert}, ${h.slots}, ${h.lagerUnits}, ${h.vitrineSlots}, ${h.energyRegenPct}`)),
    'on conflict (tier) do update set key = excluded.key, min_level = excluded.min_level, price_base_cents = excluded.price_base_cents,',
    '  wohnwert = excluded.wohnwert, slots = excluded.slots, lager_units = excluded.lager_units, vitrine_slots = excluded.vitrine_slots,',
    '  energy_regen_pct = excluded.energy_regen_pct;',
    'insert into game.furniture_defs (key, slot, slot_index, rank, min_level, price_base_cents, wohnwert, stat, op, value) values',
    rows(
      FURNITURE.map((f) => {
        const slot = FURNISHING_SLOTS.findIndex((s) => s.key === f.slot)
        const s = FURNISHING_SLOTS[slot]!
        return `${q(f.key)}, ${q(f.slot)}, ${slot}, ${f.rank}, ${f.minLevel}, ${f.priceBaseCents}, ${f.wohnwert}, ${q(s.stat)}, ${q(s.op)}, ${f.value}`
      }),
    ),
    'on conflict (key) do update set slot = excluded.slot, slot_index = excluded.slot_index, rank = excluded.rank, min_level = excluded.min_level,',
    '  price_base_cents = excluded.price_base_cents, wohnwert = excluded.wohnwert, stat = excluded.stat, op = excluded.op, value = excluded.value;',
    'insert into game.cosmetic_defs (key, kind, min_level, price_base_cents, title) values',
    rows(COSMETICS.map((c) => `${q(c.key)}, ${q(c.kind)}, ${c.minLevel}, ${c.priceBaseCents}, ${q(c.title)}`)),
    'on conflict (key) do update set kind = excluded.kind, min_level = excluded.min_level, price_base_cents = excluded.price_base_cents,',
    '  title = excluded.title;',
    'insert into game.job_defs (key, min_level, wage, minigame, shifts) values',
    rows(JOBS.map((j) => `${q(j.key)}, ${j.minLevel}, ${j.wage}, ${q(j.minigame)}, ${j.shifts}`)),
    'on conflict (key) do update set min_level = excluded.min_level, wage = excluded.wage, minigame = excluded.minigame, shifts = excluded.shifts;',
    'insert into game.consumable_defs (key, price_base_cents, pfandbons, energy, booster, buff_stat, buff_op, buff_value, buff_minutes) values',
    rows(
      CONSUMABLES.map(
        (c) =>
          `${q(c.key)}, ${c.priceBaseCents ?? 'null'}, ${c.pfandbons ?? 'null'}, ${c.energy ?? 0}, ${c.booster ?? 0}, ${q(c.buff?.stat)}, ${q(c.buff?.op)}, ${c.buff?.value ?? 'null'}, ${c.buff?.minutes ?? 'null'}`,
      ),
    ),
    'on conflict (key) do update set price_base_cents = excluded.price_base_cents, pfandbons = excluded.pfandbons, energy = excluded.energy,',
    '  booster = excluded.booster, buff_stat = excluded.buff_stat, buff_op = excluded.buff_op, buff_value = excluded.buff_value,',
    '  buff_minutes = excluded.buff_minutes;',
    'insert into game.achievement_defs (key, event, tiers, titles) values',
    rows(
      ACHIEVEMENTS.map(
        (a) => `${q(a.key)}, ${q(a.event)}, ${q(JSON.stringify(a.tiers))}::jsonb, ${q(JSON.stringify(a.titles ?? []))}::jsonb`,
      ),
    ),
    'on conflict (key) do update set event = excluded.event, tiers = excluded.tiers, titles = excluded.titles;',
    'insert into game.store_defs (key, min_level, markup_bps, closed_sunday, restocks, stock_per_player, lim, lim_per_ruf100, products) values',
    rows(
      STORES.map(
        (st) =>
          `${q(st.key)}, ${st.minLevel}, ${st.markupBps}, ${st.closedSunday}, ${q(JSON.stringify(st.restocks ?? []))}::jsonb, ${st.stockPerPlayer ?? 0}, ${st.limit}, ${st.limitPerRuf100 ?? 0}, ${q(JSON.stringify(st.products))}::jsonb`,
      ),
    ),
    'on conflict (key) do update set min_level = excluded.min_level, markup_bps = excluded.markup_bps, closed_sunday = excluded.closed_sunday,',
    '  restocks = excluded.restocks, stock_per_player = excluded.stock_per_player, lim = excluded.lim, lim_per_ruf100 = excluded.lim_per_ruf100,',
    '  products = excluded.products;',
    'insert into game.rivals (id, name, start_base_cents, growth_pct, start_level, level_per_day, start_collection_pct) values',
    rows(RIVALS.map((r) => `${q(r.id)}, ${q(r.name)}, ${r.startBaseCents}, ${r.growthPct}, ${r.startLevel}, ${r.levelPerDay}, ${r.startCollectionPct}`)),
    'on conflict (id) do update set name = excluded.name, start_base_cents = excluded.start_base_cents, growth_pct = excluded.growth_pct,',
    '  start_level = excluded.start_level, level_per_day = excluded.level_per_day, start_collection_pct = excluded.start_collection_pct;',
    'insert into game.goal_defs (key, set_id, groups, stat, op, value, min_grade) values',
    rows(GOALS.map((g) => `${q(g.key)}, ${q(g.set)}, ${q(JSON.stringify(g.groups))}::jsonb, ${q(g.bonus.stat)}, ${q(g.bonus.op)}, ${g.bonus.value}, ${g.minGrade ?? 'null'}`)),
    'on conflict (key) do update set set_id = excluded.set_id, groups = excluded.groups, stat = excluded.stat, op = excluded.op, value = excluded.value,',
    '  min_grade = excluded.min_grade;',
    'insert into game.npcs (id, name, archetype, ruf, budget_base_cents, activity, params) values',
    rows(NPCS.map((n) => `${q(n.id)}, ${q(n.name)}, ${q(n.archetype)}, ${n.ruf}, ${n.budgetBaseCents}, ${n.activity}, ${q(JSON.stringify(n.params))}::jsonb`)),
    'on conflict (id) do update set name = excluded.name, archetype = excluded.archetype, ruf = excluded.ruf,',
    '  budget_base_cents = excluded.budget_base_cents, activity = excluded.activity, params = excluded.params;',
    'insert into game.tutorial_steps (step, event, reward_booster, reward_base_cents, reward_ep) values',
    rows(TUTORIAL.map((s, i) => `${i}, ${q(s.event)}, ${s.reward.booster ?? 0}, ${s.reward.cents ?? 0}, ${s.reward.ep ?? 0}`)),
    'on conflict (step) do update set event = excluded.event, reward_booster = excluded.reward_booster,',
    '  reward_base_cents = excluded.reward_base_cents, reward_ep = excluded.reward_ep;',
    `delete from game.tutorial_steps where step >= ${TUTORIAL.length};`,
    '',
  )
  return out.join('\n')
}

if (process.argv[1]?.endsWith('gen-seed.ts')) {
  writeFileSync(new URL('../supabase/seed/config.sql', import.meta.url), buildConfigSql())
  writeFileSync(new URL('../supabase/seed/catalog.sql', import.meta.url), buildCatalogSql())
  console.log('wrote supabase/seed/config.sql and catalog.sql')
}

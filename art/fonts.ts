/**
 * Own bitmap fonts, drawn in code. Glyph notation: rows from top to bottom separated by `|`,
 * `#` is ink. Rows sit on the baseline; rows after `_` hang below it (descenders); a leading `^`
 * hangs the glyph from the cap line instead (quotes, asterisk). Glyphs are proportional.
 */
export interface Font {
  name: string
  /** Height of capital letters in pixels. */
  cap: number
  /** Rows a descender may reach below the baseline. */
  descent: number
  /** Width of a space. */
  space: number
  glyphs: ReadonlyMap<string, Glyph>
}

interface Glyph {
  w: number
  /** Offset of the first row from the cap line. */
  top: number
  rows: readonly string[]
}

function font(
  name: string,
  cap: number,
  descent: number,
  space: number,
  table: Readonly<Record<string, string>>,
): Font {
  const glyphs = new Map<string, Glyph>()
  for (const [ch, src] of Object.entries(table)) {
    const hung = src.startsWith('^')
    const [above = '', below = ''] = (hung ? src.slice(1) : src).split('_')
    const up = above.split('|')
    const rows = below === '' ? up : [...up, ...below.split('|')]
    glyphs.set(ch, { w: Math.max(...rows.map((r) => r.length)), top: hung ? 0 : cap - up.length, rows })
  }
  return { name, cap, descent, space, glyphs }
}


export const FONTS: readonly Font[] = [REGULAR, CONDENSED, MICRO]

/** Characters every font covers. */
export const CHARSET = [...REGULAR.glyphs.keys()].join('')

/** Width of a text in pixels (one pixel between glyphs). */
export function measure(text: string, f: Font): number {
  let w = 0
  for (const ch of text) w += (ch === ' ' ? f.space : ((f.glyphs.get(ch) ?? f.glyphs.get('?'))?.w ?? 0)) + 1
  return Math.max(0, w - 1)
}

/** The first font in which the text fits into `maxWidth` (regular → condensed → micro). */
export function fit(text: string, maxWidth: number, fonts: readonly Font[] = FONTS): Font {
  return fonts.find((f) => measure(text, f) <= maxWidth) ?? fonts[fonts.length - 1] ?? MICRO
}

/** Break a text into lines that fit `maxWidth`, at spaces and after hyphens. */
export function wrap(text: string, f: Font, maxWidth: number): string[] {
  const lines: string[] = []
  let line = ''
  for (const word of text.split(' ')) {
    for (const chunk of word.split(/(?<=-)/)) {
      const glue = line === '' || line.endsWith('-') ? '' : ' '
      if (line !== '' && measure(line + glue + chunk, f) > maxWidth) {
        lines.push(line)
        line = chunk
      } else line += glue + chunk
    }
  }
  if (line !== '') lines.push(line)
  return lines
}

/**
 * Fit a name into a box: one line in the first font that fits, otherwise two lines in the micro
 * font (only there do two lines with descenders fit a header).
 */
export function fitLines(text: string, maxWidth: number): { font: Font; lines: string[] } {
  const font = fit(text, maxWidth)
  if (measure(text, font) <= maxWidth) return { font, lines: [text] }
  return { font: MICRO, lines: wrap(text, MICRO, maxWidth).slice(0, 2) }
}

export interface TextOptions {
  /** `x` is the left edge (default), the centre or the right edge of the text. */
  align?: 'left' | 'center' | 'right'
  /** Drop shadow one pixel down and right. */
  shadow?: RGB
  /** One-pixel outline around every glyph. */
  outline?: RGB
}

/** Draw a text; `y` is the top of the capital letters. Returns the width drawn. */
export function drawText(
  p: Painter,
  text: string,
  x: number,
  y: number,
  f: Font,
  color: RGB,
  o: TextOptions = {},
): number {
  const width = measure(text, f)
  const left = o.align === 'right' ? x - width + 1 : o.align === 'center' ? x - Math.floor(width / 2) : x
  const ink = (dx: number, dy: number, c: RGB) => {
    let cx = left + dx
    for (const ch of text) {
      if (ch === ' ') {
        cx += f.space + 1
        continue
      }
      const g = f.glyphs.get(ch) ?? f.glyphs.get('?')
      if (!g) continue
      g.rows.forEach((row, j) => {
        for (let i = 0; i < row.length; i++) if (row[i] === '#') p.set(cx + i, y + dy + g.top + j, c)
      })
      cx += g.w + 1
    }
  }
  if (o.outline !== undefined) {
    for (let dy = -1; dy <= 1; dy++)
      for (let dx = -1; dx <= 1; dx++) if (dx !== 0 || dy !== 0) ink(dx, dy, o.outline)
  }
  if (o.shadow !== undefined) ink(1, 1, o.shadow)
  ink(0, 0, color)
  return width
}
